#!/usr/bin/env python3
"""
OCP SRV CMS - Cassandra configuration generator (configure_cassandra.py)

Builds the effective cassandra.yaml from:
  1. the stock cassandra.yaml shipped with the Cassandra release (release defaults)
  2. cassandra-overrides.yaml (benchmark settings)
  3. MEMTABLE_ALLOCATION_TYPE and CASSANDRA_YAML_OVERRIDES from the environment

CASSANDRA_YAML_OVERRIDES is a comma separated list of key=value pairs. Each value is parsed
as YAML, so numbers, booleans and null work as expected, e.g.:
    CASSANDRA_YAML_OVERRIDES="concurrent_reads=64,trickle_fsync=false,key_cache_size=1GiB"

Usage:
    python3 configure_cassandra.py <stock_yaml> <overrides_yaml> <output_yaml>
"""

import os
import sys

import yaml


def log(msg):
    print(f"[CONFIG] {msg}")


def parse_env_overrides(text):
    overrides = {}
    for item in filter(None, (p.strip() for p in text.split(","))):
        if "=" not in item:
            raise ValueError(f"CASSANDRA_YAML_OVERRIDES entry '{item}' is not key=value")
        key, val = item.split("=", 1)
        overrides[key.strip()] = yaml.safe_load(val.strip())
    return overrides


def main():
    if len(sys.argv) != 4:
        print(f"Usage: {sys.argv[0]} <stock_yaml> <overrides_yaml> <output_yaml>")
        sys.exit(1)
    stock_path, overrides_path, out_path = sys.argv[1:]

    with open(stock_path) as f:
        config = yaml.safe_load(f)
    with open(overrides_path) as f:
        overrides = yaml.safe_load(f) or {}

    memtable_type = os.environ.get("MEMTABLE_ALLOCATION_TYPE", "").strip()
    if memtable_type:
        overrides["memtable_allocation_type"] = memtable_type
    overrides.update(parse_env_overrides(os.environ.get("CASSANDRA_YAML_OVERRIDES", "")))

    for key, val in overrides.items():
        if key not in config:
            log(f"NOTE: '{key}' is not set in the stock cassandra.yaml (commented out there, or misspelled)")
        log(f"{key}: {config.get(key)!r} -> {val!r}")
        config[key] = val

    with open(out_path, "w") as f:
        f.write("# Generated by configure_cassandra.py: stock cassandra.yaml + cassandra-overrides.yaml + env\n")
        yaml.safe_dump(config, f, default_flow_style=False, sort_keys=False)
    log(f"Wrote {out_path} ({len(overrides)} overrides)")


if __name__ == "__main__":
    main()
